class TestGroParsing:
    def test_valid_file(self) -> None:
        gro = read_gro(VALID / "system.gro")
        assert gro.n_atoms == 68
        assert gro.positions.shape == (68, 3)
        assert gro.box[:3] == (3.0, 3.0, 3.0)
        assert gro.positions_finite
        assert gro.residue_names[0] == "POL"
        assert gro.atom_names[0] == "C1"

    def test_truncated_file_is_rejected(self, tmp_path: Path) -> None:
        from polymer_engine.core.errors import SystemValidationError

        path = tmp_path / "short.gro"
        path.write_text("title\n100\n" + "".join(f"{1:5d}{'POL':<5s}{'C':>5s}{i:5d}{0.0:8.3f}{0.0:8.3f}{0.0:8.3f}\n" for i in range(3)))
        with pytest.raises(SystemValidationError, match="truncated"):
            read_gro(path)

    def test_non_integer_atom_count_is_rejected(self, tmp_path: Path) -> None:
        from polymer_engine.core.errors import SystemValidationError

        path = tmp_path / "bad.gro"
        path.write_text("title\nnot-a-number\n1 1 1\n")
        with pytest.raises(SystemValidationError, match="not an integer"):
            read_gro(path)

    def test_too_few_lines(self, tmp_path: Path) -> None:
        from polymer_engine.core.errors import SystemValidationError

        path = tmp_path / "tiny.gro"
        path.write_text("only one line\n")
        with pytest.raises(SystemValidationError):
            read_gro(path)


class TestTopologyParsing:
    def test_includes_and_molecule_types_resolve(self) -> None:
        topology = read_topology(VALID / "topol.top", include_dirs=[VALID])
        assert topology.molecule_types["POL"].n_atoms == 8
        assert topology.molecule_types["SOL"].n_atoms == 3
        assert topology.molecules == [("POL", 1), ("SOL", 20)]
        assert topology.total_atoms == 68
        assert topology.missing_includes == []

    def test_library_includes_are_not_missing_files(self, tmp_path: Path) -> None:
        path = tmp_path / "topol.top"
        path.write_text('#include <charmm36.ff/forcefield.itp>\n\n[ molecules ]\nSOL 1\n')
        topology = read_topology(path)
        assert "charmm36.ff/forcefield.itp" in topology.includes
        assert topology.missing_includes == [], "angle-bracket includes resolve at run time"

    def test_missing_local_include_is_recorded(self, tmp_path: Path) -> None:
        path = tmp_path / "topol.top"
        path.write_text('#include "absent.itp"\n\n[ molecules ]\nSOL 1\n')
        assert read_topology(path).missing_includes == ["absent.itp"]

    def test_circular_includes_terminate(self, tmp_path: Path) -> None:
        (tmp_path / "a.itp").write_text('#include "b.itp"\n')
        (tmp_path / "b.itp").write_text('#include "a.itp"\n')
        topology = read_topology(tmp_path / "a.itp")
        assert topology.missing_includes == []

    def test_ifdef_blocks_are_honoured(self, tmp_path: Path) -> None:
        path = tmp_path / "topol.top"
        path.write_text(
            "[ moleculetype ]\nA 3\n[ atoms ]\n1 x 1 A a 1 0 1\n"
            "#ifdef POSRES\n[ moleculetype ]\nB 3\n[ atoms ]\n1 x 1 B b 1 0 1\n#endif\n"
            "[ molecules ]\nA 1\n"
        )
        topology = read_topology(path)
        assert "A" in topology.molecule_types
        assert "B" not in topology.molecule_types, "an inactive #ifdef block must not define a type"


class TestXvgParsing:
    def test_metadata_and_data(self, tmp_path: Path) -> None:
        path = tmp_path / "density.xvg"
        path.write_text(
            '# generated by gmx energy\n'
            '@    title "Density"\n'
            '@    xaxis  label "Time (ps)"\n'
            '@    yaxis  label "kg/m\\S3\\N"\n'
            '@ s0 legend "Density"\n'
            "0.0  1000.0\n10.0 1010.0\n20.0  995.0\n"
        )
        data = read_xvg(path)
        assert data.n_points == 3
        assert data.title == "Density"
        assert data.legends == ["Density"]
        assert data.y.tolist() == [1000.0, 1010.0, 995.0]

    def test_ragged_rows_are_rejected(self, tmp_path: Path) -> None:
        from polymer_engine.core.errors import SystemValidationError

        path = tmp_path / "bad.xvg"
        path.write_text("0 1 2\n1 2\n")
        with pytest.raises(SystemValidationError, match="Ragged"):
            read_xvg(path)

    def test_empty_data_is_rejected(self, tmp_path: Path) -> None:
        from polymer_engine.core.errors import SystemValidationError

        path = tmp_path / "empty.xvg"
        path.write_text("# only comments\n@ title \"nothing\"\n")
        with pytest.raises(SystemValidationError, match="no numeric data"):
            read_xvg(path)


