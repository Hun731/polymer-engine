VALID = Path(__file__).resolve().parents[1] / "fixtures" / "systems" / "valid_system"


@pytest.fixture
def system(tmp_path: Path) -> Path:
    target = tmp_path / "system"
    shutil.copytree(VALID, target)
    return target


def gate(report, name: str):
    return next(g for g in report.gates if g.gate == name)


