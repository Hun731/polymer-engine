class TestManifest:
    def test_manifest_records_a_digest_per_file(self, system: Path) -> None:
        manifest = build_manifest(system)
        assert len(manifest.artifacts) == 4
        assert all(len(a.sha256) == 64 for a in manifest.artifacts)
        assert Path(manifest.coordinates).name == "system.gro"
        assert Path(manifest.topology).name == "topol.top"

    def test_manifest_round_trips(self, system: Path, tmp_path: Path) -> None:
        from polymer_engine.simulation.system import SystemManifest

        original = build_manifest(system)
        path = original.write(tmp_path / "m.json")
        restored = SystemManifest.load(path)
        assert restored.coordinates == original.coordinates
        assert len(restored.artifacts) == len(original.artifacts)

    def test_replica_gro_files_do_not_shadow_the_system_coordinates(self, system: Path) -> None:
        """A per-stage .gro in a subdirectory must not be picked as system input."""
        replica = system / "replica_01"
        replica.mkdir()
        (replica / "npt.gro").write_text((system / "system.gro").read_text())
        assert Path(build_manifest(system).coordinates).name == "system.gro"


class TestImport:
    def test_archive_import_end_to_end(self, tmp_path: Path) -> None:
        archive = tmp_path / "job.tgz"
        with tarfile.open(archive, "w:gz") as tf:
            tf.add(VALID, arcname="charmm-gui-1234")
        graph = ProvenanceGraph()
        imported = import_archive(archive, tmp_path / "out", graph=graph, source={"provider": "charmm_gui"})
        assert imported.usable is True
        assert imported.manifest.source["archive_sha256"]
        assert imported.artifact_id is not None
        # lineage: system -> archive
        assert graph.ancestors(imported.artifact_id)

    def test_archive_with_missing_topology_is_not_usable(self, tmp_path: Path) -> None:
        staging = tmp_path / "staging"
        shutil.copytree(VALID, staging)
        (staging / "topol.top").unlink()
        archive = tmp_path / "bad.tgz"
        with tarfile.open(archive, "w:gz") as tf:
            tf.add(staging, arcname="job")
        imported = import_archive(archive, tmp_path / "out")
        assert imported.usable is False

    def test_directory_import(self, system: Path) -> None:
        imported = import_directory(system)
        assert imported.usable is True
        assert imported.extraction is None
