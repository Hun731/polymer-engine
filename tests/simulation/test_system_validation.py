class TestValidation:
    def test_a_valid_system_passes_every_gate(self, system: Path) -> None:
        report = validate_system(system)
        assert report.status is GateStatus.PASS
        assert report.promotable is True

    def test_atom_counts_are_actually_checked(self, system: Path) -> None:
        assert gate(validate_system(system), "topology_matches_coordinates").value == 68

    def test_missing_topology_fails(self, system: Path) -> None:
        (system / "topol.top").unlink()
        report = validate_system(system)
        assert gate(report, "topology_present").status is GateStatus.FAIL
        assert report.promotable is False

    def test_missing_coordinates_fails(self, system: Path) -> None:
        (system / "system.gro").unlink()
        report = validate_system(system)
        assert gate(report, "coordinates_present").status is GateStatus.FAIL
        assert report.promotable is False

    def test_missing_include_fails(self, system: Path) -> None:
        (system / "water.itp").unlink()
        report = validate_system(system)
        assert gate(report, "topology_includes").status is GateStatus.FAIL
        assert report.promotable is False

    def test_atom_count_mismatch_fails(self, system: Path) -> None:
        """Change the topology so it no longer describes the coordinate file."""
        top = system / "topol.top"
        top.write_text(top.read_text().replace("SOL         20", "SOL         19"))
        report = validate_system(system)
        mismatch = gate(report, "topology_matches_coordinates")
        assert mismatch.status is GateStatus.FAIL
        assert mismatch.value == 68 and mismatch.threshold == 65

    def test_unresolvable_molecule_type_is_inconclusive_not_pass(self, system: Path) -> None:
        """Cannot verify is not the same as verified."""
        (system / "water.itp").write_text("; emptied\n")
        report = validate_system(system)
        assert gate(report, "topology_matches_coordinates").status is GateStatus.INCONCLUSIVE
        assert report.promotable is False, "inconclusive must block promotion"

    def test_non_finite_coordinates_fail(self, system: Path) -> None:
        gro = system / "system.gro"
        lines = gro.read_text().splitlines()
        lines[2] = lines[2][:20] + f"{'NaN':>8s}" + lines[2][28:]
        gro.write_text("\n".join(lines) + "\n")
        report = validate_system(system)
        assert gate(report, "coordinates_finite").status is GateStatus.FAIL

    def test_missing_box_fails_when_required(self, system: Path) -> None:
        gro = system / "system.gro"
        lines = gro.read_text().splitlines()
        gro.write_text("\n".join(lines[:-1]) + "\n")
        assert gate(validate_system(system), "box_defined").status is GateStatus.FAIL
        assert gate(validate_system(system, require_box=False), "box_defined").status is GateStatus.WARN

    def test_zero_box_dimension_fails(self, system: Path) -> None:
        gro = system / "system.gro"
        lines = gro.read_text().splitlines()
        lines[-1] = f"{0.0:10.5f}{3.0:10.5f}{3.0:10.5f}"
        gro.write_text("\n".join(lines) + "\n")
        assert gate(validate_system(system), "box_defined").status is GateStatus.FAIL

    def test_contents_larger_than_the_box_fail(self, system: Path) -> None:
        """A molecule wider than its periodic box interacts with its own image."""
        gro = system / "system.gro"
        lines = gro.read_text().splitlines()
        lines[-1] = f"{0.5:10.5f}{0.5:10.5f}{0.5:10.5f}"
        gro.write_text("\n".join(lines) + "\n")
        assert gate(validate_system(system), "contents_fit_box").status is GateStatus.FAIL

    def test_missing_molecules_section_fails(self, system: Path) -> None:
        top = system / "topol.top"
        text = top.read_text()
        top.write_text(text[: text.index("[ molecules ]")])
        assert gate(validate_system(system), "molecules_section").status is GateStatus.FAIL

    def test_empty_directory_fails(self, tmp_path: Path) -> None:
        empty = tmp_path / "nothing"
        empty.mkdir()
        report = validate_system(empty)
        assert report.promotable is False

    def test_nonexistent_directory_fails(self, tmp_path: Path) -> None:
        report = validate_system(tmp_path / "absent")
        assert report.status is GateStatus.FAIL


